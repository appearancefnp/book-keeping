export type Lang = 'lv' | 'en' | 'ru';
export type MsgKey = keyof typeof EN;

/** Intl locale for date/number formatting per UI language. */
export const LOCALE_FOR: Record<Lang, string> = { lv: 'lv-LV', ru: 'ru-RU', en: 'en-GB' };

export function messagesFor(lang: Lang): Record<MsgKey, string> {
  if (lang === 'lv') return LV;
  if (lang === 'ru') return RU;
  return EN;
}
